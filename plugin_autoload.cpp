int Autoload_SyncVDF(const char *szRelDir, const std::set<std::string> &skip)
{
	if (!szRelDir || !szRelDir[0])
		return 0;

	std::string base = g_SMAPI->GetBaseDir();
	std::string mmDir = base + "/addons/metamod";
	std::string relDir = szRelDir;
	while (!relDir.empty() && (relDir.back() == '/' || relDir.back() == '\\'))
		relDir.pop_back();

	std::vector<std::string> binaries = ListBinaries(base + "/" + relDir);
	std::vector<VdfEntry> vdfs = ListVdfs(mmDir);
	std::set<std::string> usedNames;
	for (const VdfEntry &v : vdfs)
		usedNames.insert(Lower(v.vdfName));

	int nCreated = 0, nFixed = 0, nRemoved = 0;
	std::set<std::string> wanted;
	for (const std::string &rel : binaries)
	{
		std::string stem = Stem(rel);
		if (skip.count(stem) || skip.count(rel))
			continue;
		std::string file = relDir + "/" + StripExt(rel);
		wanted.insert(Lower(file));

		bool ok = false;
		for (const VdfEntry &v : vdfs)
			if (Lower(v.file) == Lower(file)) { ok = true; break; }
		if (ok)
			continue;

		VdfEntry *pOld = nullptr;
		bool bForeign = false;
		for (VdfEntry &v : vdfs)
		{
			if (Lower(Stem(v.file + kBinaryExt)) != Lower(stem))
				continue;
			if (v.generated)
			{
				pOld = &v;
				break;
			}
			if (FileExists(base + "/" + v.file + kBinaryExt))
			{
				ConColorMsg(Color(255, 165, 0, 255), "[utils] Plugins: %s skipped, %s already loads \"%s\"\n", rel.c_str(), v.vdfName.c_str(), v.file.c_str());
				bForeign = true;
				break;
			}
			ConColorMsg(Color(255, 165, 0, 255), "[utils] Plugins: %s points to missing \"%s\" (not touched), remove it by hand\n", v.vdfName.c_str(), v.file.c_str());
		}
		if (bForeign)
			continue;
		if (pOld)
		{
			std::string oldFile = pOld->file;
			if (WriteVdf(mmDir + "/" + pOld->vdfName, stem, file))
			{
				ConColorMsg(Color(255, 165, 0, 255), "[utils] Plugins: %s: \"%s\" -> \"%s\"\n", pOld->vdfName.c_str(), oldFile.c_str(), file.c_str());
				pOld->file = file;
				nFixed++;
			}
			continue;
		}

		std::string name = stem + ".vdf";
		for (int i = 2; usedNames.count(Lower(name)); i++)
			name = stem + "_" + std::to_string(i) + ".vdf";
		if (WriteVdf(mmDir + "/" + name, stem, file))
		{
			usedNames.insert(Lower(name));
			vdfs.push_back({name, file, true});
			ConColorMsg(Color(255, 165, 0, 255), "[utils] Plugins: created %s -> \"%s\"\n", name.c_str(), file.c_str());
			nCreated++;
		}
		else
			ConColorMsg(Color(255, 0, 0, 255), "[utils] Plugins: can't write %s/%s\n", mmDir.c_str(), name.c_str());
	}

	for (const VdfEntry &v : vdfs)
	{
		if (!v.generated || wanted.count(Lower(v.file)))
			continue;
		if (Lower(v.file).rfind(Lower(relDir) + "/", 0) != 0)
			continue;
		if (remove((mmDir + "/" + v.vdfName).c_str()) == 0)
			nRemoved++;
	}

	if (nCreated || nFixed || nRemoved)
		ConColorMsg(Color(0, 255, 0, 255), "[utils] Plugins: vdf created %d, fixed %d, removed %d\n", nCreated, nFixed, nRemoved);
	
	return nCreated + nFixed;
}
