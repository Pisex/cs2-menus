#ifdef _WIN32
const char *kBinaryExt = ".dll";
#else
const char *kBinaryExt = ".so";
#endif

bool EndsWith(const std::string &s, const std::string &suffix)
{
	return s.size() >= suffix.size() && s.compare(s.size() - suffix.size(), suffix.size(), suffix) == 0;
}

struct ScanState
{
	std::vector<std::string> out;
#ifndef _WIN32
	std::set<std::pair<dev_t, ino_t>> seenDirs;
	std::set<std::pair<dev_t, ino_t>> seenFiles;
#endif
};

bool IsDisabledDir(const std::string &name)
{
	if (name.size() != 8)
		return false;
	for (size_t i = 0; i < 8; i++)
		if (tolower((unsigned char)name[i]) != "disabled"[i])
			return false;
	return true;
}

void ListBinariesRec(const std::string &root, const std::string &rel, ScanState &state, int depth)
{
	if (depth > 16)
		return;
	std::string dir = rel.empty() ? root : root + "/" + rel;
#ifdef _WIN32
	WIN32_FIND_DATAA fd;
	HANDLE h = FindFirstFileA((dir + "\\*").c_str(), &fd);
	if (h == INVALID_HANDLE_VALUE)
		return;
	std::vector<std::string> files, dirs;
	do
	{
		std::string name = fd.cFileName;
		if (name[0] == '.')
			continue;
		if (IsDisabledDir(name))
			continue;
		if (fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)
		{
			if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_REPARSE_POINT))
				dirs.push_back(name);
		}
		else if (EndsWith(name, kBinaryExt))
			files.push_back(name);
	} while (FindNextFileA(h, &fd));
	FindClose(h);
	std::sort(files.begin(), files.end());
	std::sort(dirs.begin(), dirs.end());
	for (const std::string &name : files)
		state.out.push_back(rel.empty() ? name : rel + "/" + name);
	for (const std::string &name : dirs)
		ListBinariesRec(root, rel.empty() ? name : rel + "/" + name, state, depth + 1);
#else
	struct stat dst;
	if (stat(dir.c_str(), &dst) != 0 || !state.seenDirs.insert({dst.st_dev, dst.st_ino}).second)
		return;
	DIR *d = opendir(dir.c_str());
	if (!d)
		return;
	std::vector<std::string> files, dirs;
	while (dirent *e = readdir(d))
	{
		std::string name = e->d_name;
		if (name[0] == '.')
			continue;
		if (IsDisabledDir(name))
			continue;
		struct stat st;
		if (stat((dir + "/" + name).c_str(), &st) != 0)
			continue;
		if (S_ISDIR(st.st_mode))
			dirs.push_back(name);
		else if (S_ISREG(st.st_mode) && EndsWith(name, kBinaryExt) && state.seenFiles.insert({st.st_dev, st.st_ino}).second)
			files.push_back(name);
	}
	closedir(d);
	std::sort(files.begin(), files.end());
	std::sort(dirs.begin(), dirs.end());
	for (const std::string &name : files)
		state.out.push_back(rel.empty() ? name : rel + "/" + name);
	for (const std::string &name : dirs)
		ListBinariesRec(root, rel.empty() ? name : rel + "/" + name, state, depth + 1);
#endif
}

std::vector<std::string> ListBinaries(const std::string &dir)
{
	ScanState state;
	ListBinariesRec(dir, "", state, 0);
	return state.out;
}

std::string Stem(const std::string &relPath)
{
	size_t slash = relPath.find_last_of("/\\");
	std::string file = slash == std::string::npos ? relPath : relPath.substr(slash + 1);
	return file.substr(0, file.size() - strlen(kBinaryExt));
}

const char *kVdfMarker = "// generated by utils autoload";

bool ReadFile(const std::string &path, std::string &out)
{
	std::ifstream f(path, std::ios::binary);
	if (!f)
		return false;
	out.assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
	return true;
}

std::string VdfFile(const std::string &text)
{
	size_t pos = 0;
	while ((pos = text.find("\"file\"", pos)) != std::string::npos)
	{
		size_t q1 = text.find('"', pos + 6);
		size_t nl = text.find('\n', pos);
		if (q1 == std::string::npos || (nl != std::string::npos && q1 > nl))
		{
			pos += 6;
			continue;
		}
		size_t q2 = text.find('"', q1 + 1);
		if (q2 == std::string::npos)
			return "";
		std::string v = text.substr(q1 + 1, q2 - q1 - 1);
		for (char &ch : v)
			if (ch == '\\')
				ch = '/';
		return v;
	}
	return "";
}

std::string StripExt(std::string s)
{
	if (EndsWith(s, kBinaryExt))
		s.resize(s.size() - strlen(kBinaryExt));
	return s;
}

bool FileExists(const std::string &path)
{
	std::ifstream f(path, std::ios::binary);
	return (bool)f;
}

std::string Lower(std::string s)
{
	for (char &ch : s)
		ch = (char)tolower((unsigned char)ch);
	return s;
}

struct VdfEntry
{
	std::string vdfName;
	std::string file;
	bool generated;
};

std::vector<VdfEntry> ListVdfs(const std::string &dir)
{
	std::vector<std::string> names;
#ifdef _WIN32
	WIN32_FIND_DATAA fd;
	HANDLE h = FindFirstFileA((dir + "\\*.vdf").c_str(), &fd);
	if (h != INVALID_HANDLE_VALUE)
	{
		do
			names.push_back(fd.cFileName);
		while (FindNextFileA(h, &fd));
		FindClose(h);
	}
#else
	if (DIR *d = opendir(dir.c_str()))
	{
		while (dirent *e = readdir(d))
		{
			std::string n = e->d_name;
			if (n.size() > 4 && Lower(n.substr(n.size() - 4)) == ".vdf")
				names.push_back(n);
		}
		closedir(d);
	}
#endif
	std::vector<VdfEntry> out;
	for (const std::string &n : names)
	{
		std::string text;
		if (!ReadFile(dir + "/" + n, text))
			continue;
		out.push_back({n, StripExt(VdfFile(text)), text.find(kVdfMarker) != std::string::npos});
	}
	return out;
}

bool WriteVdf(const std::string &path, const std::string &alias, const std::string &file)
{
	std::ofstream f(path, std::ios::binary | std::ios::trunc);
	if (!f)
		return false;
	f << kVdfMarker << "\n\"Metamod Plugin\"\n{\n\t\"alias\"\t\"" << alias << "\"\n\t\"file\"\t\"" << file << "\"\n}\n";
	return (bool)f;
}

